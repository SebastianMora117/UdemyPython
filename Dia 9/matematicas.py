import math

resultado =  math.floor(3.7) #redondea hacia abajo
print(resultado)

resultado = math.ceil(3.2) #redondea hacia arriba
print(resultado)

resultado = math.pi #imprime pi
print(resultado)

resultado = math.log(100, 10) #calcula el logaritmo de un número en una base específica
print(resultado)

resultado = math.tan(100) #calcula la tangente de un ángulo dado en radianes
print(resultado)

resultado = math.cos(100) #calcula el coseno de un ángulo dado en radianes
print(resultado)